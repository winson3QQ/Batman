#!/bin/bash
# tests/wbox/gen/gen.sh BATMAN_TREE OUTDIR [VARIANT...] — regenerate tests/wbox/<name>.patch from edits.pl
# (254-h23 §4.2). BATMAN_TREE = a checkout that has the P1b seams and this harness (the tree the firmware pins);
# a throwaway worktree of it is used, never the checkout itself. Each patch is checked: it applies to a clean tree,
# a Go variant builds (arm64, -tags prov_test) with its witness in the binary, shell files parse. Then copy OUTDIR's
# patches to tests/wbox/ and run scripts/lint-wbox.sh (which also checks helpers.list).
#   GO=<go> (default: the go in PATH)
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=$(cd "${1:?usage: gen.sh BATMAN_TREE OUTDIR [VARIANT...]}" && pwd); OUT=${2:?OUTDIR}; shift 2
GO=${GO:-$(command -v go)}; GOFMT=${GOFMT:-$(dirname "$GO")/gofmt}
[ -x "$GO" ] || { echo "no Go (set GO=)"; exit 1; }
export GOFLAGS=-mod=vendor GOTOOLCHAIN=local
BASE=$(git -C "$SRC" rev-parse HEAD)
W=$(mktemp -d); T=$(mktemp -d); trap 'git -C "$SRC" worktree remove --force "$W" >/dev/null 2>&1; rm -rf "$W" "$T"' EXIT
git -C "$SRC" worktree add -q --detach "$W" "$BASE"
mkdir -p "$OUT"
VARIANTS=${*:-$(perl -ne 'print "$1\n" if /^\t'"'"'([a-z0-9-]+)'"'"' => sub \{/' "$HERE/edits.pl")}
bad=0
for v in $VARIANTS; do
	git -C "$W" checkout -q -- . && git -C "$W" clean -qfdx
	wit=$(cd "$W" && perl "$HERE/edits.pl" "$v" 2>&1) || { echo "BAD  $v: edits: $wit"; bad=$((bad+1)); continue; }
	desc=$(cd "$W" && perl "$HERE/edits.pl" --describe "$v")
	git -C "$W" checkout -q -- . && git -C "$W" clean -qfdx
	(cd "$W" && perl "$HERE/edits.pl" "$v" >/dev/null)
	git -C "$W" add -A feed
	files=$(git -C "$W" diff --cached --name-only)
	{ echo "# wbox $v: $desc"; echo "# wbox-witness: $wit"; echo "# generated by tests/wbox/gen/gen.sh (254-h23 §4.2) on $BASE"
	  git -C "$W" diff --cached --binary; } > "$OUT/$v.patch"
	git -C "$W" reset -q; git -C "$W" checkout -q -- . && git -C "$W" clean -qfdx
	msg=""
	git -C "$W" apply --check "$OUT/$v.patch" 2>/dev/null || msg="$msg apply-check"
	git -C "$W" apply "$OUT/$v.patch" 2>/dev/null
	for f in $files; do case "$f" in
		*.go) ;;
		*.sh|*/uci-defaults/*|*/init.d/*) sh -n "$W/$f" 2>/dev/null || msg="$msg sh-n:$f" ;;
	esac; done
	if echo "$files" | grep -q '\.go$'; then
		fmt=$(cd "$W/feed/batman-prov/src" && "$GOFMT" -l . 2>&1); [ -z "$fmt" ] || msg="$msg gofmt:[$fmt]"
		(cd "$W/feed/batman-prov/src" && GOCACHE=$T/gc GOARCH=arm64 CGO_ENABLED=0 "$GO" build -trimpath -buildvcs=false -tags prov_test -ldflags='-s -w' -o "$T/h" ./cmd/batman-provhelper 2>"$T/err") \
			|| msg="$msg build:[$(head -3 "$T/err" | tr '\n' ' ')]"
		[ -f "$T/h" ] && { [ "$(strings "$T/h" | grep -c -- "$wit")" -ge 1 ] || msg="$msg witness-not-in-binary"; rm -f "$T/h"; }
	fi
	if [ -z "$msg" ]; then echo "ok   $v ($wit): $(echo $files | tr ' ' ',')"; else echo "BAD  $v:$msg"; bad=$((bad+1)); fi
done
echo "RESULT gen: $bad bad"; [ $bad = 0 ]
